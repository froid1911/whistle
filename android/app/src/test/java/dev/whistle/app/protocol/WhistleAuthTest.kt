/**
 * Cross-side signing fixtures (v2, server challenge): `whistle_fixture_go_v2.json` is signed by the
 * bridge's Go code and must verify here with this side's canonicalization;
 * `whistle_fixture_kotlin_v2.json` is produced by [writesKotlinFixture] (build/whistle-fixtures/)
 * and committed to bridge/internal/devauth/testdata, where Go verifies it (TestKotlinFixtureV2).
 * A copy in the test resources is re-verified here. The v1 Go fixture is still read for its
 * welcome signature (the welcome format did not change).
 */
class WhistleAuthTest {
    private fun resource(name: String): String? = javaClass.getResource("/whistle/$name")?.readText()

    private fun JsonObject.s(k: String) = this[k]!!.jsonPrimitive.content

    private fun checkFixture(f: JsonObject) {
        val body = f.s("body").toByteArray(Charsets.UTF_8)
        assertEquals(f.s("body_sha256"), WhistleAuth.sha256Hex(body))
        val ts = f["ts"]!!.jsonPrimitive.long
        val canonical = WhistleAuth.canonical(f.s("method"), f.s("path"), f.s("host"), ts, f.s("nonce"), f.s("body_sha256"), f.s("challenge"), f.s("device_id"))
        assertEquals(f.s("canonical"), canonical)
        assertTrue(canonical.startsWith("whistle-v2\n"))
        val spki = Base64.getDecoder().decode(f.s("public_key"))
        assertTrue("signature verifies", WhistleAuth.verify(spki, canonical, f.s("sig")))
        assertEquals(f.s("authorization"), WhistleAuth.header(f.s("device_id"), ts, f.s("nonce"), f.s("challenge"), f.s("body_sha256"), f.s("sig")))
        assertTrue(WhistleAuth.isChallenge(f.s("challenge")))
        // Tampering anything breaks it (the device id and the challenge are signed too).
        assertFalse(WhistleAuth.verify(spki, canonical.replace("POST", "GET"), f.s("sig")))
        assertFalse(WhistleAuth.verify(spki, canonical.removeSuffix(f.s("device_id")) + "dother", f.s("sig")))
        assertFalse(WhistleAuth.verify(spki, canonical.replace(f.s("challenge"), "AAAAAAAAAAAAAAAAAAAAAA"), f.s("sig")))
    }

    @Test
    fun verifiesGoFixtureV2() {
        checkFixture(WireJson.parseToJsonElement(resource("whistle_fixture_go_v2.json")!!).jsonObject)
    }

    @Test
    fun verifiesGoWelcomeSignature() {
        val f = WireJson.parseToJsonElement(resource("whistle_fixture_go.json")!!).jsonObject
        val spki = Base64.getDecoder().decode(f.s("public_key"))
        val w = f["welcome"]!!.jsonObject
        assertEquals(w.s("message"), WhistleAuth.welcomeMessage(w.s("server_id"), w.s("nonce")))
        assertTrue("welcome sig verifies", WhistleAuth.verify(spki, w.s("message"), w.s("sig")))
        assertFalse(WhistleAuth.verify(spki, WhistleAuth.welcomeMessage(w.s("server_id"), "other"), w.s("sig")))
        assertEquals(f.s("empty_body_sha256"), WhistleAuth.EMPTY_BODY_HASH)
    }

    @Test
    fun writesKotlinFixture() {
        val keys = SoftwareDeviceKeys()
        val spki = keys.generate("fixture")
        val body = "--b\r\nContent-Disposition: form-data; name=\"file\"; filename=\"ü.png\"\r\n\r\n\u0000ÿ whistle\r\n--b--\r\n"
        val ts = 1762693200L
        val nonce = "_-8AAQIDBAUGBwgJCgsMDQ"
        val challenge = "IA8gISIjJCUmJygpKissLQ"
        val device = "dfedcba987654"
        val path = "/v1/upload?pane_id=w1%3Ap2"
        val host = "100.64.0.10:8787"
        val hash = WhistleAuth.sha256Hex(body.toByteArray(Charsets.UTF_8))
        val canonical = WhistleAuth.canonical("POST", path, host, ts, nonce, hash, challenge, device)
        val sig = WhistleAuth.b64url(keys.sign("fixture", canonical.toByteArray(Charsets.UTF_8)))
        val f = buildJsonObject {
            put("comment", "Generated by the Android app's WhistleAuthTest.writesKotlinFixture (SoftwareDeviceKeys). Whistle v2 auth. Verified by bridge/internal/devauth TestKotlinFixtureV2.")
            put("public_key", Base64.getEncoder().encodeToString(spki))
            put("device_id", device)
            put("method", "POST")
            put("path", path)
            put("host", host)
            put("ts", ts)
            put("nonce", nonce)
            put("challenge", challenge)
            put("body", body)
            put("body_sha256", hash)
            put("canonical", canonical)
            put("sig", sig)
            put("authorization", WhistleAuth.header(device, ts, nonce, challenge, hash, sig))
        }
        checkFixture(f)
        File("build/whistle-fixtures").mkdirs()
        File("build/whistle-fixtures/whistle_fixture_kotlin_v2.json").writeText(WireJson.encodeToString(JsonObject.serializer(), f) + "\n")
        // The committed copy (shared with the bridge's tests) still verifies.
        checkFixture(WireJson.parseToJsonElement(resource("whistle_fixture_kotlin_v2.json")!!).jsonObject)
    }

    @Test
    fun signerSignsWhatOkHttpSends() {
        val keys = SoftwareDeviceKeys()
        val spki = keys.generate("a")
        val m = Machine("m", "myserver", "http://100.64.0.10:8787", deviceId = "d1", keyAlias = "a", bridgeKey = "x")
        val signer = RequestSigner(keys, nowSeconds = { 1000 })
        val url = "http://100.64.0.10:8787/v1/upload".toHttpUrl().newBuilder().addQueryParameter("pane_id", "w1:p1").build()
        val ch = "EBESExQVFhcYGRobHB0eHw"
        val s = signer.sign(m, "POST", url, ch, WhistleAuth.sha256Hex("x".toByteArray()))!!
        assertTrue(s.authorization.startsWith("Whistle v2 device=d1, ts=1000, nonce="))
        val parts = s.authorization.removePrefix("Whistle v2 ").split(", ").associate { it.substringBefore('=') to it.substringAfter('=') }
        assertEquals("d1", parts["device"])
        assertEquals("1000", parts["ts"])
        assertEquals(s.nonce, parts["nonce"])
        assertEquals(ch, parts["challenge"])
        assertEquals(WhistleAuth.sha256Hex("x".toByteArray()), parts["body"])
        assertEquals(22, s.nonce.length) // 16 bytes base64url
        assertEquals("/v1/upload?pane_id=" + url.encodedQuery!!.substringAfter('='), WhistleAuth.pathAndQuery(url))
        val msg = WhistleAuth.canonical("POST", WhistleAuth.pathAndQuery(url), "100.64.0.10:8787", 1000, s.nonce, WhistleAuth.sha256Hex("x".toByteArray()), ch, "d1")
        assertTrue(WhistleAuth.verify(spki, msg, parts["sig"]!!))
        // Unpaired machine: no signature (legacy).
        assertEquals(null, signer.sign(m.unpaired(), "GET", url, ch))
        assertEquals("[::1]:8787", WhistleAuth.host("http://[::1]:8787/".toHttpUrl()))
        assertEquals("example.com", WhistleAuth.host("http://example.com/".toHttpUrl()))
        assertFalse(WhistleAuth.isChallenge("short"))
        assertFalse(WhistleAuth.isChallenge("EBESExQVFhcYGRobHB0eH+"))
    }

    /** The QR as the bridge's pair action prints it (half blocks, light modules printed) decodes with ZXing. */
    @Test
    fun decodesBridgeTerminalQr() {
        val lines = resource("pair_qr.txt")!!.trimEnd('\n').split('\n')
        val uri = lines.first()
        val rows = lines.drop(1)
        val w = rows.maxOf { it.length }
        val modules = ArrayList<BooleanArray>() // true = printed (light)
        for (r in rows) {
            val top = BooleanArray(w)
            val bot = BooleanArray(w)
            r.forEachIndexed { x, ch ->
                top[x] = ch == '█' || ch == '▀'
                bot[x] = ch == '█' || ch == '▄'
            }
            modules += top
            modules += bot
        }
        val scale = 6
        fun render(printedIsLight: Boolean): ByteArray {
            val img = ByteArray(w * scale * modules.size * scale)
            for (y in modules.indices) for (x in 0 until w) {
                val light = modules[y][x] == printedIsLight
                val v = (if (light) 0xF0 else 0x10).toByte()
                for (dy in 0 until scale) for (dx in 0 until scale) img[(y * scale + dy) * w * scale + x * scale + dx] = v
            }
            return img
        }
        val d = QrDecoder()
        // Dark terminal (printed blocks are light) and light terminal (inverted).
        assertEquals(uri, d.decode(render(true), w * scale, modules.size * scale))
        assertEquals(uri, d.decode(render(false), w * scale, modules.size * scale))
        val invite = PairInvites.parse(d.decode(render(true), w * scale, modules.size * scale)!!)
        assertEquals("100.64.0.10:8787", invite.address)
        assertEquals("myserver", invite.name)
        assertNotNull(invite.fingerprint)
    }
}
